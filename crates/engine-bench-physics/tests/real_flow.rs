//! Real-fluid flow against `CoolProp`: choked mass flux and throat pressure
//! along `CoolProp`'s own isentropes, for dense gases, condensing CO2 vapour
//! and steam (the homogeneous equilibrium model inside the dome); and nozzle
//! thrust continuity across the back-pressure regimes.

use engine_bench_physics::{
    flow::{
        Nozzle, Orifice, PerfectGas, Reservoir,
        real::{FlowState, RealFluid, Stagnation},
    },
    fluid::{FrozenVapour, PureFluid, TabulatedFluid},
    steam::Water,
    units::{
        Area, Pressure, SpecificHeatCapacity, ThermodynamicTemperature, area::square_meter,
        force::newton, mass_rate::kilogram_per_second, pressure::pascal,
        specific_heat_capacity::joule_per_kilogram_kelvin, thermodynamic_temperature::kelvin,
    },
};

/// Choked flux, kg/(m²·s), and throat pressure, Pa: the flow through a 1 m²
/// orifice with Cd = 1 into vacuum, and the pressure where that flux peaks.
fn choked<F: RealFluid>(fluid: &F, stagnation: &Stagnation) -> anyhow::Result<f64> {
    let orifice = Orifice::new(Area::new::<square_meter>(1.0), 1.0)?;
    Ok(orifice
        .real_mass_flow(fluid, stagnation, Pressure::new::<pascal>(0.0))?
        .get::<kilogram_per_second>())
}

fn pure_at(fluid: PureFluid, p: f64, t: f64) -> anyhow::Result<FlowState> {
    let props = fluid.properties(
        Pressure::new::<pascal>(p),
        ThermodynamicTemperature::new::<kelvin>(t),
    )?;
    fluid.state_prho(props.pressure, props.density)
}

fn close(label: &str, got: f64, want: f64, tolerance: f64) -> anyhow::Result<()> {
    let error = (got / want - 1.0).abs();
    anyhow::ensure!(error < tolerance, "{label}: {got} vs {want} ({error:e})");
    Ok(())
}

#[test]
#[allow(clippy::unreadable_literal, reason = "generated golden values")]
fn test_real_flow_choked_flux_matches_coolprop() -> anyhow::Result<()> {
    // Generated by tools/reference/real_flow_golden.py: choked flux kg/(m² s).
    let argon = Stagnation::at_rest(&pure_at(PureFluid::Argon, 2e7, 300.0)?);
    close(
        "argon dense",
        choked(&PureFluid::Argon, &argon)?,
        64719.35179922115,
        1e-7,
    )?;
    let helium = Stagnation::at_rest(&pure_at(PureFluid::Helium, 3e7, 300.0)?);
    close(
        "helium dense",
        choked(&PureFluid::Helium, &helium)?,
        26616.236208469425,
        1e-7,
    )?;
    // This isentrope chokes where it grazes the dome 0.4 K below the critical
    // point: the flux peaks at the kink on the saturation line, which each
    // code places by its own near-critical equilibrium solve (3e-6 apart).
    let co2 = Stagnation::at_rest(&pure_at(PureFluid::CarbonDioxide, 1e7, 320.0)?);
    let flux = choked(&PureFluid::CarbonDioxide, &co2)?;
    close("CO2 supercritical", flux, 42858.22713051999, 1e-5)?;
    // Saturated vapour condenses as it expands: the equilibrium mixture chokes.
    let t = ThermodynamicTemperature::new::<kelvin>(280.0);
    let sat = PureFluid::CarbonDioxide.saturation(t)?;
    let vapour = Stagnation::at_rest(
        &PureFluid::CarbonDioxide.state_prho(sat.pressure, sat.vapour_density)?,
    );
    close(
        "CO2 saturated vapour",
        choked(&PureFluid::CarbonDioxide, &vapour)?,
        13765.874443776613,
        1e-7,
    )?;
    // CoolProp evaluates nitrogen at a reducing density 1.3e-7 off the
    // published one.
    let nitrogen = Stagnation::at_rest(&pure_at(PureFluid::Nitrogen, 2e7, 300.0)?);
    close(
        "nitrogen dense",
        choked(&PureFluid::Nitrogen, &nitrogen)?,
        48370.067949537515,
        1e-6,
    )?;
    // Steam shares CoolProp's IF97 reference state; the golden isentropes are
    // built from its exact forward (p, T) and saturated (p, Q) calls.
    for (label, p0, s0, flux) in [
        (
            "steam superheated",
            1e6,
            6825.0529123961105,
            1421.533384533392,
        ),
        (
            "steam saturated vapour",
            5e5,
            6820.58078422402,
            735.5537582113028,
        ),
        ("steam wet", 1e5, 4330.683407421976, 214.01642263354728),
    ] {
        let state = Water.state_ps(
            Pressure::new::<pascal>(p0),
            SpecificHeatCapacity::new::<joule_per_kilogram_kelvin>(s0),
        )?;
        close(
            label,
            choked(&Water, &Stagnation::at_rest(&state))?,
            flux,
            1e-6,
        )?;
    }
    Ok(())
}

#[test]
fn test_real_nozzle_thrust_is_continuous_across_regimes() -> anyhow::Result<()> {
    // Dense nitrogen through ε = 4: thrust just either side of each regime
    // boundary agrees, so a simulation sweeping back pressure sees no jumps.
    let nozzle = Nozzle::new(
        Area::new::<square_meter>(1e-5),
        Area::new::<square_meter>(4e-5),
    )?;
    let fluid = PureFluid::Nitrogen;
    let chamber = Stagnation::at_rest(&pure_at(fluid, 2e7, 300.0)?);
    let thrust = |pb: f64| -> anyhow::Result<f64> {
        Ok(nozzle
            .real_operating_point(&fluid, &chamber, Pressure::new::<pascal>(pb))?
            .thrust
            .get::<newton>())
    };
    // Locate the boundaries from the operating point at a few back pressures.
    let design = nozzle.real_operating_point(&fluid, &chamber, Pressure::new::<pascal>(0.0))?;
    let p_design = design.exit_pressure.get::<pascal>();
    let mut pb = 1e5;
    while pb < 1.9e7 {
        let (below, above) = (thrust(pb * (1.0 - 1e-7))?, thrust(pb * (1.0 + 1e-7))?);
        anyhow::ensure!(
            (below - above).abs() < 1e-4 * below.abs().max(1.0),
            "jump at {pb} Pa: {below} vs {above}"
        );
        pb *= 1.25;
    }
    let (below, above) = (
        thrust(p_design * (1.0 - 1e-7))?,
        thrust(p_design * (1.0 + 1e-7))?,
    );
    anyhow::ensure!(
        (below - above).abs() < 1e-4 * below,
        "jump at the design pressure"
    );
    Ok(())
}

#[test]
fn test_frozen_nitrogen_nozzle_expands_below_the_triple_point() -> anyhow::Result<()> {
    // A vacuum cold-gas nozzle, area ratio 50, from 20 bar and 300 K: the
    // exit is far below N2's 63.15 K triple point. Frozen vapour expands
    // there; at 20 bar and 300 K N2 is within ~0.3 % of a perfect gas, so the
    // thrust matches the γ = 1.4 nozzle closely.
    let nozzle = Nozzle::new(
        Area::new::<square_meter>(1e-6),
        Area::new::<square_meter>(5e-5),
    )?;
    let fluid = FrozenVapour::new(PureFluid::Nitrogen);
    let chamber = Stagnation::at_rest(&pure_at(PureFluid::Nitrogen, 2e6, 300.0)?);
    let vacuum = Pressure::new::<pascal>(0.0);
    let real = nozzle.real_operating_point(&fluid, &chamber, vacuum)?;
    let exit_t = real.exit_temperature.get::<kelvin>();
    anyhow::ensure!(exit_t < 63.0, "exit at {exit_t} K");
    let air_like = PerfectGas::new(
        1.4,
        SpecificHeatCapacity::new::<joule_per_kilogram_kelvin>(8.314_462_618 / 0.028_013_4),
    )?;
    let reservoir = Reservoir::new(
        Pressure::new::<pascal>(2e6),
        ThermodynamicTemperature::new::<kelvin>(300.0),
        air_like,
    )?;
    let ideal = nozzle.operating_point(&reservoir, vacuum)?;
    close(
        "thrust",
        real.thrust.get::<newton>(),
        ideal.thrust.get::<newton>(),
        1e-2,
    )?;
    close(
        "mass flow",
        real.mass_flow.get::<kilogram_per_second>(),
        ideal.mass_flow.get::<kilogram_per_second>(),
        1e-2,
    )?;
    // Equilibrium (HEM) would have to condense here, and fails below the
    // triple point.
    let eq = nozzle.real_operating_point(&PureFluid::Nitrogen, &chamber, vacuum);
    anyhow::ensure!(
        eq.is_err(),
        "equilibrium expansion below the triple point: {eq:?} vs {real:?}"
    );
    Ok(())
}

#[test]
fn test_tabulated_fluids_give_the_exact_flows() -> anyhow::Result<()> {
    // Choked flux and a frozen vacuum nozzle through the tables against the
    // exact equations (the tables agree with them to ~1e-6).
    let orifice = Orifice::new(Area::new::<square_meter>(1e-6), 1.0)?;
    let nozzle = Nozzle::new(
        Area::new::<square_meter>(1e-6),
        Area::new::<square_meter>(2.5e-5),
    )?;
    let vacuum = Pressure::new::<pascal>(0.0);
    for fluid in [PureFluid::Nitrogen, PureFluid::CarbonDioxide] {
        let (equilibrium, frozen) = (
            TabulatedFluid::equilibrium(fluid)?,
            TabulatedFluid::frozen(fluid)?,
        );
        let start = match fluid {
            PureFluid::CarbonDioxide => {
                let t = ThermodynamicTemperature::new::<kelvin>(290.0);
                let sat = fluid.saturation(t)?;
                fluid.state_prho(sat.pressure, sat.vapour_density)?
            }
            _ => pure_at(fluid, 2e7, 300.0)?,
        };
        let chamber = Stagnation::at_rest(&start);
        let exact = orifice
            .real_mass_flow(&fluid, &chamber, vacuum)?
            .get::<kilogram_per_second>();
        let table = orifice
            .real_mass_flow(&equilibrium, &chamber, vacuum)?
            .get::<kilogram_per_second>();
        close(&format!("{fluid:?} choked flux"), table, exact, 2e-6)?;
        // Saturated CO2 vapour this close to the critical point reaches the
        // vapour spinodal within the nozzle; a superheated chamber does not.
        let hot = Stagnation::at_rest(&match fluid {
            PureFluid::CarbonDioxide => pure_at(fluid, 2e6, 320.0)?,
            _ => start,
        });
        // CO2 stays within the frozen vapour's range only for a modest
        // expansion (deeper, it is far supersaturated over the solid).
        let nozzle = match fluid {
            PureFluid::CarbonDioxide => Nozzle::new(
                Area::new::<square_meter>(1e-6),
                Area::new::<square_meter>(2e-6),
            )?,
            _ => nozzle,
        };
        let exact = nozzle.real_operating_point(&FrozenVapour::new(fluid), &hot, vacuum)?;
        let table = nozzle.real_operating_point(&frozen, &hot, vacuum)?;
        close(
            &format!("{fluid:?} frozen thrust"),
            table.thrust.get::<newton>(),
            exact.thrust.get::<newton>(),
            1e-5,
        )?;
    }
    Ok(())
}

#[test]
fn test_frozen_nitrogen_reaches_area_ratio_100_in_vacuum() -> anyhow::Result<()> {
    // From a 10 bar, 290 K plenum the exit of an area-ratio-100 vacuum nozzle
    // is below half N2's triple temperature, at a few hundred Pa: so dilute
    // that N2 is nearly a perfect gas there.
    let nozzle = Nozzle::new(
        Area::new::<square_meter>(1e-6),
        Area::new::<square_meter>(1e-4),
    )?;
    let chamber = Stagnation::at_rest(&pure_at(PureFluid::Nitrogen, 1e6, 290.0)?);
    let vacuum = Pressure::new::<pascal>(0.0);
    let real =
        nozzle.real_operating_point(&FrozenVapour::new(PureFluid::Nitrogen), &chamber, vacuum)?;
    let exit_t = real.exit_temperature.get::<kelvin>();
    anyhow::ensure!(exit_t < 31.6, "exit at {exit_t} K");
    let gas = PerfectGas::new(
        1.4,
        SpecificHeatCapacity::new::<joule_per_kilogram_kelvin>(8.314_462_618 / 0.028_013_4),
    )?;
    let reservoir = Reservoir::new(
        Pressure::new::<pascal>(1e6),
        ThermodynamicTemperature::new::<kelvin>(290.0),
        gas,
    )?;
    let ideal = nozzle.operating_point(&reservoir, vacuum)?;
    close(
        "exit temperature",
        exit_t,
        ideal.exit_temperature.get::<kelvin>(),
        1e-2,
    )?;
    close(
        "thrust",
        real.thrust.get::<newton>(),
        ideal.thrust.get::<newton>(),
        5e-3,
    )
}
