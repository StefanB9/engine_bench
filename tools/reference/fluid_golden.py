"""Golden values for `crates/engine-bench-physics/tests/reference_fluids.rs`, from CoolProp's
reference (HEOS) equations of state.

    venv/bin/python tools/reference/fluid_golden.py > golden.rs

h and s are given relative to an ideal-gas-like anchor state (300 K, 1 mol/m³), because the
Rust equations use NASA's reference state instead of each equation's own.
"""
import CoolProp.CoolProp as CP

FLUIDS = [("Nitrogen", "Nitrogen"), ("Argon", "Argon"), ("Helium", "Helium"), ("CarbonDioxide", "CarbonDioxide")]
STATES = {  # (T K, rho mol/m3), across gas, dense supercritical, liquid
    "Nitrogen": [(300, 40), (300, 4000), (300, 12000), (200, 6000), (100, 25000), (150, 11000), (126.5, 11200), (80, 29000)],
    "Argon": [(300, 40), (300, 4000), (300, 12000), (200, 9000), (100, 33500), (151, 13400), (120, 30000), (90, 35000)],
    "Helium": [(300, 40), (300, 4000), (300, 12000), (100, 6000), (20, 8000), (6, 15000), (4, 33000), (5.3, 17000)],
    "CarbonDioxide": [(300, 40), (300, 4000), (350, 12000), (250, 24500), (220, 26800), (305, 10600), (304.2, 10700), (400, 8000)],
}


def row(*xs):
    return "    [" + ", ".join(f"{x:.15e}" for x in xs) + "],"


def main():
    print("// Generated by tools/reference/fluid_golden.py (CoolProp 8.0.0, HEOS).")
    for name, fluid in FLUIDS:
        h0 = CP.PropsSI("Hmolar", "T", 300, "Dmolar", 1.0, fluid)
        s0 = CP.PropsSI("Smolar", "T", 300, "Dmolar", 1.0, fluid)
        print(f"/// {name} single phase: T K, rho mol/m³, p Pa, cv, cp J/(mol·K), w m/s, h − h(300 K, 1 mol/m³) J/mol, s − s(…) J/(mol·K).")
        print(f'#[allow(clippy::unreadable_literal, clippy::excessive_precision, reason = "generated golden values")]')
        print(f"const {name.upper()}_STATES: &[[f64; 8]] = &[")
        for t, rho in STATES[name]:
            g = lambda k: CP.PropsSI(k, "T", t, "Dmolar", rho, fluid)
            print(row(t, rho, g("P"), g("Cvmolar"), g("Cpmolar"), g("A"), g("Hmolar") - h0, g("Smolar") - s0))
        print("];")
        print(f"/// {name} at (T, p): T K, p Pa, rho mol/m³ of the stable phase.")
        print(f'#[allow(clippy::unreadable_literal, clippy::excessive_precision, reason = "generated golden values")]')
        print(f"const {name.upper()}_PT: &[[f64; 3]] = &[")
        tc, tt = CP.PropsSI("Tcrit", fluid), CP.PropsSI("Ttriple", fluid)
        for t in (tt + 1.0, 0.5 * (tt + tc), 0.95 * tc, 1.1 * tc, 300.0):
            for p in (1e5, 1e6, 1e7, 3e7):
                try:
                    rho = CP.PropsSI("Dmolar", "T", t, "P", p, fluid)
                except ValueError:
                    continue  # below the melting line: solid, which the Rust code does not model
                print(row(t, p, rho))
        print("];")
        print(f"/// {name} saturation: T K, p Pa, rho' mol/m³, rho'' mol/m³.")
        print(f'#[allow(clippy::unreadable_literal, clippy::excessive_precision, reason = "generated golden values")]')
        print(f"const {name.upper()}_SATURATION: &[[f64; 4]] = &[")
        for frac in (0.0, 0.2, 0.5, 0.8, 0.95, 0.99):
            t = tt + 0.001 + frac * (tc - tt - 0.002)
            print(row(t, CP.PropsSI("P", "T", t, "Q", 0, fluid), CP.PropsSI("Dmolar", "T", t, "Q", 0, fluid),
                      CP.PropsSI("Dmolar", "T", t, "Q", 1, fluid)))
        print("];")


if __name__ == "__main__":
    main()
