"""Transcribes reference Helmholtz equations of state from CoolProp's fluid files into Rust
(`crates/engine-bench-physics/src/fluid/coefficients/`).

    curl -O https://raw.githubusercontent.com/CoolProp/CoolProp/master/dev/fluids/Nitrogen.json  # etc.
    python3 tools/reference/gen_fluids.py <dir with the JSON files> <output dir>

The lead and enthalpy/entropy-offset terms of alpha0 only fix each equation's reference state;
they are dropped, and the Rust code re-derives them so h and s match the NASA ideal-gas data.
"""
import json, sys

FLUIDS = [  # (CoolProp file, Rust module, const, NASA species name)
    ("Nitrogen", "nitrogen", "NITROGEN", "N2"),
    ("Argon", "argon", "ARGON", "Ar"),
    ("Helium", "helium", "HELIUM", "He"),
    ("CarbonDioxide", "carbon_dioxide", "CARBON_DIOXIDE", "CO2"),
]

HEADER = """// Generated by `tools/reference/gen_fluids.py` from CoolProp's `dev/fluids/{file}.json`
// (https://github.com/CoolProp/CoolProp). {eos}.
// Copyright (c) 2012-2018 Ian H. Bell and other CoolProp developers, MIT licence: permission is
// hereby granted, free of charge, to any person obtaining a copy of this software and associated
// documentation files (the "Software"), to deal in the Software without restriction, including
// without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense,
// and/or sell copies of the Software, subject to the following conditions: The above copyright
// notice and this permission notice shall be included in all copies or substantial portions of
// the Software. THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.
"""


def num(v):
    r = repr(float(v))
    if "e" in r:
        m, e = r.split("e")
        if "." not in m:
            m += ".0"
        return f"{m}e{int(e)}"
    return r


def integer(v):
    assert float(v) == int(v), v
    return str(int(v))


def ancillary(a):
    form = {"rhoLnoexp": "LiquidDensity", "rhoV": "VapourDensity"}[a["type"]]
    terms = ", ".join(f"({num(n)}, {num(t)})" for n, t in zip(a["n"], a["t"]))
    return (f"Ancillary {{ form: AncillaryForm::{form}, using_tau: {'true' if a['using_tau_r'] else 'false'}, "
            f"t_reducing: {num(a['T_r'])}, reducing_value: {num(a['reducing_value'])}, terms: &[{terms}] }}")


def main():
    src, out = sys.argv[1], sys.argv[2]
    for file, module, const, species in FLUIDS:
        d = json.load(open(f"{src}/{file}.json"))
        eos = d["EOS"][0]
        red = eos["STATES"]["reducing"]
        log_tau, ideal_power, planck = 0.0, [], []
        for term in eos["alpha0"]:
            kind = term["type"]
            if kind == "IdealGasHelmholtzLogTau":
                log_tau += term["a"]
            elif kind == "IdealGasHelmholtzPower":
                ideal_power += list(zip(term["n"], term["t"]))
            elif kind == "IdealGasHelmholtzPlanckEinstein":
                planck += list(zip(term["n"], term["t"]))
            elif kind == "IdealGasHelmholtzPlanckEinsteinFunctionT":
                planck += [(n, v / term["Tcrit"]) for n, v in zip(term["n"], term["v"])]
            elif kind in ("IdealGasHelmholtzLead", "IdealGasHelmholtzEnthalpyEntropyOffset"):
                pass  # reference state only, re-derived from NASA data
            else:
                raise SystemExit(f"{file}: unsupported alpha0 term {kind}")
        power, gaussian, non_analytic = [], [], []
        for term in eos["alphar"]:
            kind = term["type"]
            if kind == "ResidualHelmholtzPower":
                for n, dd, t, l in zip(term["n"], term["d"], term["t"], term["l"]):
                    power.append(f"Power {{ n: {num(n)}, d: {integer(dd)}, t: {num(t)}, l: {integer(l)} }}")
            elif kind == "ResidualHelmholtzGaussian":
                for v in zip(*(term[k] for k in ("n", "d", "t", "eta", "epsilon", "beta", "gamma"))):
                    n, dd, t, eta, eps, beta, gamma = v
                    gaussian.append(f"Gaussian {{ n: {num(n)}, d: {integer(dd)}, t: {num(t)}, eta: {num(eta)}, "
                                    f"epsilon: {num(eps)}, beta: {num(beta)}, gamma: {num(gamma)} }}")
            elif kind == "ResidualHelmholtzNonAnalytic":
                for v in zip(*(term[k] for k in ("n", "a", "b", "beta", "A", "B", "C", "D"))):
                    n, a, b, beta, aa, bb, cc, dd2 = v
                    non_analytic.append(f"NonAnalytic {{ n: {num(n)}, a: {num(a)}, b: {num(b)}, beta: {num(beta)}, "
                                        f"big_a: {num(aa)}, big_b: {num(bb)}, big_c: {num(cc)}, big_d: {num(dd2)} }}")
            else:
                raise SystemExit(f"{file}: unsupported alphar term {kind}")
        anc = d["ANCILLARIES"]
        lines = [HEADER.format(file=file, eos=eos["BibTeX_EOS"]),
                 f"//! {file}: reference equation of state (`{eos['BibTeX_EOS']}`).", "",
                 "use super::{Ancillary, AncillaryForm, FluidData, Gaussian, " + ("NonAnalytic, " if non_analytic else "") + "Power};", "",
                 f"/// {file} (`{eos['BibTeX_EOS']}`).",
                 f"pub(crate) const {const}: FluidData = FluidData {{",
                 f'    species: "{species}",',
                 f"    gas_constant: {num(eos['gas_constant'])},",
                 f"    molar_mass: {num(eos['molar_mass'])},",
                 f"    t_crit: {num(red['T'])},",
                 f"    rho_crit: {num(red['rhomolar'])},",
                 f"    t_triple: {num(eos['Ttriple'])},",
                 f"    t_max: {num(eos['T_max'])},",
                 f"    p_max: {num(eos['p_max'])},",
                 f"    log_tau: {num(log_tau)},",
                 "    ideal_power: &[" + ", ".join(f"({num(n)}, {num(t)})" for n, t in ideal_power) + "],",
                 "    planck_einstein: &[" + ", ".join(f"({num(n)}, {num(t)})" for n, t in planck) + "],",
                 "    power: &[\n        " + ",\n        ".join(power) + ",\n    ],",
                 "    gaussian: &[\n        " + ",\n        ".join(gaussian) + ",\n    ],",
                 "    non_analytic: &[" + ("\n        " + ",\n        ".join(non_analytic) + ",\n    " if non_analytic else "") + "],",
                 f"    liquid_density: {ancillary(anc['rhoL'])},",
                 f"    vapour_density: {ancillary(anc['rhoV'])},",
                 "};", ""]
        open(f"{out}/{module}.rs", "w").write("\n".join(lines))
        print(file, len(power), len(gaussian), len(non_analytic), len(ideal_power), len(planck))


if __name__ == "__main__":
    main()
