"""Golden values for `crates/engine-bench-physics/tests/steam.rs`, from CoolProp's IF97 backend.

    python -m venv venv && venv/bin/pip install CoolProp==8.0.0
    venv/bin/python tools/reference/if97_golden.py > golden.rs

CoolProp (MIT) is used offline only; it is not a build dependency. Output rows are
(p Pa, T K, v m³/kg, h J/kg, u J/kg, s J/(kg·K), cp, cv J/(kg·K), w m/s).
"""
import CoolProp.CoolProp as CP

FLUID = "IF97::Water"


def psat(t):
    return CP.PropsSI("P", "T", t, "Q", 0, FLUID)


def b23(t):
    n1, n2, n3 = 0.34805185628969e3, -0.11671859879975e1, 0.10192970039326e-2
    return (n1 + n2 * t + n3 * t * t) * 1e6


def points():
    for t in (273.16, 300.0, 373.15, 450.0, 550.0, 620.0):  # region 1: p above saturation
        for p in (1e5, 1e6, 1e7, 5e7, 1e8):
            if p > 1.001 * psat(t):
                yield "region 1", p, t
    for t in (280.0, 400.0, 500.0, 700.0, 900.0, 1073.0):  # region 2: below saturation / B23
        for p in (700.0, 1e4, 1e5, 1e6, 1e7, 5e7, 1e8):
            below_sat = t >= 647.096 or p < 0.999 * psat(t)
            below_b23 = t <= 623.15 or t > 863.15 or p < 0.999 * b23(t)
            if below_sat and below_b23:
                yield "region 2", p, t
    for t in (1100.0, 1500.0, 2000.0, 2273.0):  # region 5
        for p in (1e4, 1e6, 1e7, 5e7):
            yield "region 5", p, t


def main():
    print("// Generated by tools/reference/if97_golden.py (CoolProp 8.0.0, IF97 backend).")
    print("const GOLDEN: &[[f64; 9]] = &[")
    region = None
    for name, p, t in points():
        if name != region:
            print(f"    // {name}")
            region = name
        keys = ("D", "H", "U", "S", "C", "O", "A")
        d, h, u, s, cp, cv, w = (CP.PropsSI(k, "T", t, "P", p, FLUID) for k in keys)
        row = [p, t, 1.0 / d, h, u, s, cp, cv, w]
        print("    [" + ", ".join(f"{x:.12e}" for x in row) + "],")
    print("];")


if __name__ == "__main__":
    main()
