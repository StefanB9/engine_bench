"""Golden choked flows for `crates/engine-bench-physics/tests/real_flow.rs`, from CoolProp.

    venv/bin/python tools/reference/real_flow_golden.py

For each stagnation state (p0, h0, s0), the mass flux along CoolProp's isentrope,
G(p) = rho(p, s0) sqrt(2 (h0 - h(p, s0))), is maximised by golden-section search on p.
Two-phase states use CoolProp's equilibrium flash (the homogeneous equilibrium model).

For IF97 water, CoolProp's (p, s) inputs return the backward equation T(p, s) unrefined
(off by millikelvins), so the isentrope is built here from exact forward (p, T) and
saturated (p, Q) calls instead.
"""
import math
import CoolProp.CoolProp as CP

CASES = [  # label, fluid, how the stagnation state is given, value 1, value 2
    ("argon dense", "Argon", "PT", 2e7, 300.0),
    ("helium dense", "Helium", "PT", 3e7, 300.0),
    ("CO2 supercritical", "CarbonDioxide", "PT", 1e7, 320.0),
    ("CO2 saturated vapour", "CarbonDioxide", "TQ", 280.0, 1.0),
    ("nitrogen dense", "Nitrogen", "PT", 2e7, 300.0),
    ("steam superheated", "IF97::Water", "PT", 1e6, 500.0),
    ("steam saturated vapour", "IF97::Water", "PQ", 5e5, 1.0),
    ("steam wet", "IF97::Water", "PQ", 1e5, 0.5),
]


def if97_ps(p, s0):
    """(rho, h) on the IF97 isentrope at p from forward calls."""
    fluid = "IF97::Water"
    sl, sv = (CP.PropsSI("S", "P", p, "Q", q, fluid) for q in (0, 1))
    if sl <= s0 <= sv:
        x = (s0 - sl) / (sv - sl)
        vl, vv = (1.0 / CP.PropsSI("D", "P", p, "Q", q, fluid) for q in (0, 1))
        hl, hv = (CP.PropsSI("H", "P", p, "Q", q, fluid) for q in (0, 1))
        return 1.0 / (vl + x * (vv - vl)), hl + x * (hv - hl)
    t_sat = CP.PropsSI("T", "P", p, "Q", 0, fluid)
    lo, hi = (t_sat * (1 + 1e-12), 1073.0) if s0 > sv else (273.16, t_sat * (1 - 1e-12))
    for _ in range(200):  # bisection on s(p, T) = s0
        mid = 0.5 * (lo + hi)
        if CP.PropsSI("S", "P", p, "T", mid, fluid) < s0:
            lo = mid
        else:
            hi = mid
    t = 0.5 * (lo + hi)
    return CP.PropsSI("D", "P", p, "T", t, fluid), CP.PropsSI("H", "P", p, "T", t, fluid)


def flux(fluid, p, h0, s0):
    if fluid == "IF97::Water":
        rho, h = if97_ps(p, s0)
    else:
        rho = CP.PropsSI("D", "P", p, "S", s0, fluid)
        h = CP.PropsSI("H", "P", p, "S", s0, fluid)
    return rho * math.sqrt(max(2.0 * (h0 - h), 0.0))


def main():
    print("// Generated by tools/reference/real_flow_golden.py (CoolProp 8.0.0).")
    print("// label, p0 Pa, h0 J/kg, s0 J/(kg K), choked flux kg/(m2 s), throat pressure Pa.")
    for label, fluid, kind, a, b in CASES:
        if kind == "PT":
            p0, h0, s0 = a, CP.PropsSI("H", "P", a, "T", b, fluid), CP.PropsSI("S", "P", a, "T", b, fluid)
        elif kind == "TQ":
            p0 = CP.PropsSI("P", "T", a, "Q", b, fluid)
            h0, s0 = CP.PropsSI("H", "T", a, "Q", b, fluid), CP.PropsSI("S", "T", a, "Q", b, fluid)
        else:
            p0, h0, s0 = a, CP.PropsSI("H", "P", a, "Q", b, fluid), CP.PropsSI("S", "P", a, "Q", b, fluid)
        lo, hi = 0.2 * p0, 0.95 * p0
        g = (math.sqrt(5) - 1) / 2
        x1, x2 = hi - g * (hi - lo), lo + g * (hi - lo)
        f1, f2 = flux(fluid, x1, h0, s0), flux(fluid, x2, h0, s0)
        while hi - lo > 1e-9 * p0:
            if f1 > f2:
                hi, x2, f2 = x2, x1, f1
                x1 = hi - g * (hi - lo)
                f1 = flux(fluid, x1, h0, s0)
            else:
                lo, x1, f1 = x1, x2, f2
                x2 = lo + g * (hi - lo)
                f2 = flux(fluid, x2, h0, s0)
        p_star = 0.5 * (lo + hi)
        print(f'    ("{label}", {p0!r}, {h0!r}, {s0!r}, {flux(fluid, p_star, h0, s0)!r}, {p_star!r}),')


if __name__ == "__main__":
    main()
